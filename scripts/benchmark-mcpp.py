#!/usr/bin/env python3
"""Reproduce the Linux portable-core comparison; run from a quiet worktree.

Requires provisioned mcpp GCC/JSON packages and host GCC with import std.
Never builds the application. Keeps logs/commands/samples under the output dir.
Temporarily changes the root manifest and xmake configuration, restoring both.
Only the std cache entry used by a cold trial is moved aside and restored.
"""

import argparse
import contextlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import statistics
import subprocess
import tempfile
import time


ROOT = Path(__file__).resolve().parents[1]
TARGETS = ["su_log", "su_diagnostics", "su_log_test", "su_log_sinks_test",
           "su_diagnostics_test", "su_control_socket_smoke_test",
           "su_control_socket_deadline_test"]
OVERLAY = """-- Generated by scripts/benchmark-mcpp.py; original targets, core only.
includes("xmake.lua")
target("su_diagnostics")
    remove_files("src/common/diagnostics/export.cpp",
                 "src/common/diagnostics/process_posix.cpp",
                 "src/common/diagnostics/export_posix.cpp")
"""
HOST = '\n[workspace.toolchain.linux]\npath = "/usr"\nfamily = "gcc"\n'


def run_clean(argv, log, *, cwd, env, records, prepare=lambda: None):
    """Retry a suspended command, reapplying its original cache/touch setup."""
    attempt = 0
    while True:
        attempt += 1
        prepare()
        attempt_log = log.with_name(f"{log.stem}-attempt-{attempt}.log")
        wall_start = float(subprocess.check_output(["date", "+%s.%N"], text=True))
        with attempt_log.open("w") as stream:
            mono_start = time.clock_gettime(time.CLOCK_MONOTONIC)
            boot_start = time.clock_gettime(time.CLOCK_BOOTTIME)
            result = subprocess.run(argv, cwd=cwd, env=env,
                                    stdout=stream, stderr=subprocess.STDOUT)
            mono_end = time.clock_gettime(time.CLOCK_MONOTONIC)
            boot_end = time.clock_gettime(time.CLOCK_BOOTTIME)
        wall_end = float(subprocess.check_output(["date", "+%s.%N"], text=True))
        mono_delta, boot_delta = mono_end - mono_start, boot_end - boot_start
        suspended = abs(boot_delta - mono_delta) > 1.0
        records.append(dict(argv=argv, cwd=str(cwd), log=attempt_log.name,
                            attempt=attempt, exit=result.returncode,
                            monotonic_start=mono_start, monotonic_end=mono_end,
                            boottime_start=boot_start, boottime_end=boot_end,
                            monotonic_seconds=mono_delta, boottime_seconds=boot_delta,
                            date_seconds=wall_end - wall_start, accepted=not suspended))
        if suspended:
            print(f"DISCARD {log.stem}: suspend detected "
                  f"(MONOTONIC={mono_delta:.3f}s, BOOTTIME={boot_delta:.3f}s); "
                  "retrying with the same preparation", flush=True)
            continue
        if result.returncode:
            raise RuntimeError(f"{shlex.join(argv)} failed; see {attempt_log}")
        return mono_delta, attempt_log


@contextlib.contextmanager
def preserve_directory(path):
    """Move an existing cache/config directory aside, including on failure."""
    with tempfile.TemporaryDirectory(prefix="s2u-mcpp-save-", dir=path.parent) as tmp:
        backup = Path(tmp) / "original"
        existed = path.exists()
        if existed:
            path.rename(backup)
        try:
            yield
        finally:
            if path.exists():
                shutil.rmtree(path)
            if existed:
                backup.rename(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--output", type=Path, default=ROOT / "build/mcpp-benchmark")
    args = parser.parse_args()
    if args.runs < 1:
        parser.error("--runs must be positive")
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    jobs = subprocess.check_output(["nproc"], text=True).strip()
    env.update(MCPP_JOBS=jobs, MCPP_OFFLINE="1", MCPP_NO_COLOR="1", NO_COLOR="1")
    env.pop("MCPP_TOOLCHAIN", None)
    env.pop("MCPP_BUILD_CACHE", None)
    # Path toolchains do not add managed ninja to PATH (unlike managed GCC).
    ninja = Path(env.get("MCPP_HOME", str(Path.home() / ".mcpp"))) / "registry/data/xpkgs/xim-x-ninja"
    candidates = sorted(ninja.glob("*/ninja"))
    if candidates:
        env["PATH"] = str(candidates[-1].parent) + os.pathsep + env["PATH"]
    elif not shutil.which("ninja"):
        parser.error("ninja is missing; provision mcpp's ninja before benchmarking")

    samples = []
    commands = []
    serial = 0

    def run(argv, name, cwd=ROOT, run_env=None, prepare=lambda: None):
        nonlocal serial
        serial += 1
        log = out / f"{serial:03d}-{name}.log"
        return run_clean(argv, log, cwd=cwd, env=run_env or env, records=commands,
                         prepare=prepare)

    def measure(tool, profile, scenario, argv, prepare=lambda: None, **kwargs):
        values = []
        for trial in range(args.runs):
            seconds, log = run(argv, f"{tool}-{profile}-{scenario}-{trial + 1}",
                               prepare=prepare, **kwargs)
            values.append(seconds)
            print(f"{tool:12s} {profile:7s} {scenario:16s} {trial + 1}: {seconds:.3f}s", flush=True)
        samples.append(dict(tool=tool, profile=profile, scenario=scenario,
                            seconds=values, median=statistics.median(values)))

    def save():
        (out / "results.json").write_text(json.dumps(dict(
            jobs=int(jobs), runs=args.runs,
            timer="CLOCK_MONOTONIC; CLOCK_BOOTTIME suspend guard (>1s); date cross-check",
            samples=samples,
            commands=commands, environment={k: env[k] for k in
                ("MCPP_JOBS", "MCPP_OFFLINE", "MCPP_NO_COLOR", "PATH")}), indent=2) + "\n")

    manifest = ROOT / "mcpp.toml"
    original = manifest.read_bytes()
    overlay = ROOT / ".mcpp-benchmark.lua"
    old_overlay = overlay.read_bytes() if overlay.exists() else None
    touched = [ROOT / "src/common/log/core.h", ROOT / "src/modules/su.control.socket.cppm"]
    timestamps = [(p, p.stat().st_atime_ns, p.stat().st_mtime_ns) for p in touched]
    std_measured = set()
    try:
        with preserve_directory(ROOT / ".xmake"):
            overlay.write_text(OVERLAY)
            for tool in ("xmake", "mcpp-host", "mcpp-managed"):
                manifest.write_bytes(original + (HOST.encode() if tool == "mcpp-host" else b""))
                for profile in ("dev", "release"):
                    label = f"{tool}-{profile}"
                    if tool == "xmake":
                        mode = "debug" if profile == "dev" else "release"
                        builddir = ROOT / "build/mcpp-benchmark-xmake" / mode
                        run(["xmake", "f", "-F", overlay.name, "-c", "-y", "-p", "linux",
                             "-a", "x86_64", "-m", mode, "--with_slint=n", "--with_seetaface=n",
                             "--ccache=n", f"--builddir={builddir}"], label + "-configure")
                        cmd = ["xmake", "build", "-F", overlay.name, "-j", jobs, *TARGETS]
                        measure(tool, profile, "cold", cmd,
                                prepare=lambda: shutil.rmtree(builddir, ignore_errors=True))
                    else:
                        cmd = ["mcpp", "test", "--workspace", "--no-run", "--profile", profile,
                               "--cache", "global"]
                        run(cmd, label + "-prepare")  # resolve/prewarm; downloads are excluded
                        database = json.loads((ROOT / "compile_commands.json").read_text())
                        (out / f"{label}-compile_commands.json").write_text(json.dumps(database, indent=2))
                        config = Path(next(r["directory"] for r in database
                                           if r["file"] == str(ROOT / "src/common/log/core.cpp")))
                        assert ROOT / "target" in config.parents
                        graph = (config / "build.ninja").read_text()
                        std_dir = Path(re.search(r"build obj/std.o : stage_file (.*)/std.o", graph)[1])
                        if std_dir not in std_measured:
                            # mcpp doesn't report std's duration; time its recorded command alone.
                            metadata = json.loads((std_dir / "std-module.json").read_text())
                            words = shlex.split(metadata["std_build_commands"][0])
                            words = words[words.index("&&") + 1:]
                            std_env = env.copy()
                            if words[0] == "env":
                                words.pop(0)
                                while "=" in words[0]:
                                    key, value = words.pop(0).split("=", 1)
                                    std_env[key] = value
                            assert words.pop() == "2>&1"
                            with tempfile.TemporaryDirectory(prefix="s2u-std-") as tmp:
                                measure(tool, "shared", "std-only", words, cwd=Path(tmp),
                                        run_env=std_env, prepare=lambda: shutil.rmtree(Path(tmp) / "gcm.cache", ignore_errors=True))
                            std_measured.add(std_dir)
                        # --cache off bypasses registry artifacts but still reads global std.
                        # Preserve that one entry and force a fresh project dir for each trial.
                        with preserve_directory(std_dir):
                            def cold():
                                shutil.rmtree(config, ignore_errors=True)
                                shutil.rmtree(std_dir, ignore_errors=True)
                            measure(tool, profile, "cold-global", [*cmd[:-1], "off"], prepare=cold)
                        measure(tool, profile, "cold-warm-global", cmd,
                                prepare=lambda: shutil.rmtree(config, ignore_errors=True))

                    measure(tool, profile, "no-op", cmd)
                    measure(tool, profile, "touch-header", cmd, prepare=touched[0].touch)
                    measure(tool, profile, "touch-module", cmd, prepare=touched[1].touch)
                    if tool == "xmake":
                        # Even --dry-run can change module scan state; capture this last.
                        run([*cmd[:6], "-v", "--dry-run", "--rebuild", *TARGETS], label + "-flags")
                    save()
    finally:
        manifest.write_bytes(original)
        if old_overlay is None:
            overlay.unlink(missing_ok=True)
        else:
            overlay.write_bytes(old_overlay)
        for path, atime, mtime in timestamps:
            os.utime(path, ns=(atime, mtime))
        save()


if __name__ == "__main__":
    main()
